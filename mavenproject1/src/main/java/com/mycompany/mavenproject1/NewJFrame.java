    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:        
        String sLowerLimitValue = lower_limit.getText();
        String sUpperLimitValue = upper_limit.getText();
        String sStepValue = step.getText();
        
        if (sLowerLimitValue.isEmpty() || sUpperLimitValue.isEmpty() || sStepValue.isEmpty()){
            JOptionPane.showMessageDialog(this, "Недостаточно данных", "Ошибка", JOptionPane.ERROR_MESSAGE);
            return;
        }    
        
        double dLowerLimitValue = 0.0, dUpperLimitValue = 0.0, dStepValue = 0.0;
        try{
            dLowerLimitValue = Double.parseDouble(lower_limit.getText());
            dUpperLimitValue = Double.parseDouble(upper_limit.getText()); 
            dStepValue = Double.parseDouble(step.getText());
        } catch (NumberFormatException e){
            JOptionPane.showMessageDialog(this, "Некорректные данные", "Ошибка", JOptionPane.ERROR_MESSAGE);
            return;
        }
                 
        
        try {
            //adding parametrs in ArrayList
            classRecIntegral exemplarRecIntegral = new classRecIntegral(dLowerLimitValue, dUpperLimitValue, dStepValue);
            arrayRecIntegral.add(exemplarRecIntegral);
            
            //adding parametrs in table
            DefaultTableModel model = (DefaultTableModel)jTable1.getModel();
            model.addRow(new Object[]{dLowerLimitValue, dUpperLimitValue, dStepValue});
            
        } catch (classRecIntegralException exc){
            JOptionPane.showMessageDialog(this, exc.getMessage(), "Исключение", JOptionPane.ERROR_MESSAGE);
        }    
        
        
    }//GEN-LAST:event_jButton1ActionPerformed

