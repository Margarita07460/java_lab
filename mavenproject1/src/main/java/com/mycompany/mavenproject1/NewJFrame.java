    private void jButton6ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton6ActionPerformed
        // TODO add your handling code here:
        JFileChooser fileChoose = new JFileChooser("C:\\02_psu\\java_lab\\mavenproject1\\");
        fileChoose.setDialogTitle("Выбор файла для чтения");
        int userSelection = fileChoose.showSaveDialog(null);

        if (userSelection == JFileChooser.APPROVE_OPTION) {
            File fileToSave = fileChoose.getSelectedFile();
            try(FileReader reader = new FileReader(fileToSave))
            {        
                Scanner scan = new Scanner (reader); 
                while (scan.hasNextLine()){
                    String[] line = scan.nextLine().split(" ");

                    //adding parametrs in ArrayList
                    classRecIntegral exemplarRecIntegral = new classRecIntegral(Double.parseDouble(line[0]), Double.parseDouble(line[1]), Double.parseDouble(line[2]));
                    exemplarRecIntegral.setRezult(Double.parseDouble(line[3]));
                    arrayRecIntegral.add(exemplarRecIntegral);

                    //adding parametrs in table
                    DefaultTableModel model = (DefaultTableModel)jTable1.getModel();
                    model.addRow(new Object[]{Double.valueOf(line[0]), Double.valueOf(line[1]), Double.valueOf(line[2]), Double.valueOf(line[3])});
                }
                reader.close();
                JOptionPane.showMessageDialog(this, "Данные успешно загружены из файла в текстовом виде", "Сообщение", JOptionPane.INFORMATION_MESSAGE);
            }
            catch(IOException ex){

                System.out.println(ex.getMessage());
            } catch (classRecIntegralException ex) {
                Logger.getLogger(NewJFrame.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_jButton6ActionPerformed

